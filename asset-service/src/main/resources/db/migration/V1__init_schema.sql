-- =====================================================================
-- Asset Service — base assetdb
-- Schéma initial : équipements, employés, affectations.
-- SQL portable PostgreSQL / H2 (mode local et tests).
-- =====================================================================

CREATE TABLE equipments (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    asset_tag      VARCHAR(64)  NOT NULL,
    name           VARCHAR(120) NOT NULL,
    type           VARCHAR(20)  NOT NULL,
    brand          VARCHAR(60),
    model          VARCHAR(60),
    serial_number  VARCHAR(80)  NOT NULL,
    purchase_date  DATE,
    status         VARCHAR(20)  NOT NULL DEFAULT 'AVAILABLE',
    CONSTRAINT pk_equipments PRIMARY KEY (id),
    CONSTRAINT uk_equipments_asset_tag UNIQUE (asset_tag),
    CONSTRAINT uk_equipments_serial_number UNIQUE (serial_number),
    CONSTRAINT ck_equipments_type CHECK (type IN
        ('LAPTOP', 'DESKTOP', 'MONITOR', 'PRINTER', 'SERVER', 'PHONE', 'TABLET', 'NETWORK', 'OTHER')),
    CONSTRAINT ck_equipments_status CHECK (status IN ('AVAILABLE', 'ASSIGNED', 'IN_MAINTENANCE', 'RETIRED'))
);

CREATE INDEX idx_equipments_status ON equipments (status);
CREATE INDEX idx_equipments_type ON equipments (type);

CREATE TABLE employees (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    first_name  VARCHAR(60)  NOT NULL,
    last_name   VARCHAR(60)  NOT NULL,
    email       VARCHAR(120) NOT NULL,
    department  VARCHAR(80),
    job_title   VARCHAR(80),
    CONSTRAINT pk_employees PRIMARY KEY (id),
    CONSTRAINT uk_employees_email UNIQUE (email)
);

CREATE TABLE assignments (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    equipment_id  BIGINT      NOT NULL,
    employee_id   BIGINT      NOT NULL,
    assigned_at   DATE        NOT NULL,
    returned_at   DATE,
    status        VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    notes         VARCHAR(500),
    CONSTRAINT pk_assignments PRIMARY KEY (id),
    CONSTRAINT fk_assignments_equipment FOREIGN KEY (equipment_id) REFERENCES equipments (id),
    CONSTRAINT fk_assignments_employee FOREIGN KEY (employee_id) REFERENCES employees (id),
    CONSTRAINT ck_assignments_status CHECK (status IN ('ACTIVE', 'RETURNED')),
    CONSTRAINT ck_assignments_dates CHECK (returned_at IS NULL OR returned_at >= assigned_at)
);

CREATE INDEX idx_assignments_equipment ON assignments (equipment_id, status);
CREATE INDEX idx_assignments_employee ON assignments (employee_id);
